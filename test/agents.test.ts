import { test } from "node:test";
import assert from "node:assert/strict";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { init, newIssue, validate } from "../src/commands.js";
import { setIssue } from "../src/set.js";
import { detectAgents, findConflicts, importsAgentsMd, parseAgents, SKILLS } from "../src/agents.js";
import { parseConfig } from "../src/config.js";

const STATUSES = ["backlog", "ready", "in-progress", "done"];
const fresh = () => mkdtempSync(join(tmpdir(), "yardhand-ai-"));
const read = (root: string, p: string) => readFileSync(join(root, p), "utf8");
const skill = (dir: string, name: string) => `${dir}/yardhand-${name}/SKILL.md`;

test("agents: AI off writes no block, no skills, and no effort line", () => {
  const root = fresh();
  const r = init(root, STATUSES, "0.0.0", false, { agents: [] });
  assert.deepEqual(r.agents, []);
  assert.deepEqual(r.blocks, []);
  assert.ok(!existsSync(join(root, "AGENTS.md")));
  assert.ok(!existsSync(join(root, ".agents")));
  assert.ok(!existsSync(join(root, ".claude")));
  assert.deepEqual(JSON.parse(read(root, "issues/yardhand.json")).agents, []);
  assert.doesNotMatch(read(root, "issues/backlog/000-maintain-repo/ISSUE.md"), /^effort:/m);
  const n = newIssue(root, { slug: "add-auth" });
  assert.doesNotMatch(read(root, n.path), /^effort:/m);
  assert.match(read(root, n.path), /^assignee:/m, "assignee stays: people use it");
  assert.deepEqual(validate(root), []);
});

test("agents: AI off keeps an effort that is set, adds it with set, and warns", () => {
  const root = fresh();
  init(root, STATUSES, "0.0.0", false, { agents: [] });
  const n = newIssue(root, { slug: "add-auth", effort: "high" });
  assert.match(read(root, n.path), /^effort: high/m);
  assert.ok(n.warnings.some((w) => /AI is off/.test(w)));
  const m = newIssue(root, { slug: "add-billing" });
  const s = setIssue(root, m.id, { effort: "low" });
  assert.match(read(root, join(s.path, "ISSUE.md")), /^effort: low/m);
  assert.ok(s.warnings.some((w) => /AI is off/.test(w)));
  const report = validate(root);
  assert.equal(report.length, 0, "a warning, never an error");
});

test("agents: codex only writes AGENTS.md and .agents/skills, not CLAUDE.md", () => {
  const root = fresh();
  const r = init(root, STATUSES, "1.2.3", false, { agents: ["codex"] });
  assert.deepEqual(r.blocks, ["AGENTS.md"]);
  for (const s of SKILLS) assert.ok(existsSync(join(root, skill(".agents/skills", s.name))), s.name);
  assert.ok(!existsSync(join(root, ".claude")));
  assert.ok(!existsSync(join(root, "CLAUDE.md")));
  const plan = read(root, skill(".agents/skills", "plan"));
  assert.match(plan, /^---\nname: yardhand-plan\ndescription: .+\n---\n/);
  assert.match(plan, /Generated by yardhand v1\.2\.3/);
  assert.match(read(root, "AGENTS.md"), /yardhand-plan/);
  assert.match(read(root, "AGENTS.md"), /For anything else, the rest of this file wins/);
});

test("agents: claude code only writes .claude/skills and a CLAUDE.md that imports AGENTS.md", () => {
  const root = fresh();
  init(root, STATUSES, "0.0.0", false, { agents: ["claude-code"] });
  for (const s of SKILLS) assert.ok(existsSync(join(root, skill(".claude/skills", s.name))), s.name);
  assert.ok(!existsSync(join(root, ".agents")), "Claude Code does not read .agents/skills");
  assert.equal(read(root, "CLAUDE.md"), "@AGENTS.md\n");
  assert.match(read(root, "AGENTS.md"), /yardhand:start/);
});

test("agents: an existing CLAUDE.md that imports AGENTS.md gets no block; one that does not gets the block", () => {
  const a = fresh();
  writeFileSync(join(a, "CLAUDE.md"), "# Mine\n@AGENTS.md\n");
  init(a, STATUSES, "0.0.0", false, { agents: ["claude-code"] });
  assert.equal(read(a, "CLAUDE.md"), "# Mine\n@AGENTS.md\n");

  const b = fresh();
  writeFileSync(join(b, "CLAUDE.md"), "# Mine\n");
  init(b, STATUSES, "0.0.0", false, { agents: ["claude-code"] });
  assert.match(read(b, "CLAUDE.md"), /# Mine[\s\S]*yardhand:start/);

  assert.ok(importsAgentsMd("x\n  @./AGENTS.md\n"));
  assert.ok(!importsAgentsMd("See @AGENTS.md for more"));
});

test("agents: removing a tool removes only the skills yardhand wrote, and never a file someone else wrote", () => {
  const root = fresh();
  init(root, STATUSES, "0.0.0", false, { agents: ["claude-code", "codex"] });
  mkdirSync(join(root, ".claude/skills/yardhand-mine"), { recursive: true });
  writeFileSync(join(root, ".claude/skills/yardhand-mine/SKILL.md"), "my own skill\n");
  const r = init(root, STATUSES, "0.0.0", true, { agents: ["codex"] });
  assert.equal(r.skills.removed.length, SKILLS.length);
  for (const s of SKILLS) assert.ok(!existsSync(join(root, skill(".claude/skills", s.name))), s.name);
  assert.equal(read(root, ".claude/skills/yardhand-mine/SKILL.md"), "my own skill\n");
  assert.ok(existsSync(join(root, skill(".agents/skills", "build"))));
});

test("agents: a hand-written skill at a yardhand path is left alone and reported", () => {
  const root = fresh();
  mkdirSync(join(root, ".agents/skills/yardhand-build"), { recursive: true });
  writeFileSync(join(root, ".agents/skills/yardhand-build/SKILL.md"), "mine\n");
  const r = init(root, STATUSES, "0.0.0", false, { agents: ["codex"] });
  assert.deepEqual(r.skills.skipped, [".agents/skills/yardhand-build/SKILL.md"]);
  assert.equal(read(root, ".agents/skills/yardhand-build/SKILL.md"), "mine\n");
});

test("agents: --force keeps the saved agents when none are given", () => {
  const root = fresh();
  init(root, STATUSES, "0.0.0", false, { agents: ["opencode"] });
  const r = init(root, STATUSES, "0.0.0", true);
  assert.deepEqual(r.agents, ["opencode"]);
});

test("agents: detection, defaults and parsing", () => {
  const root = fresh();
  assert.deepEqual(detectAgents(root), []);
  writeFileSync(join(root, "AGENTS.md"), "# Rules\n");
  assert.deepEqual(detectAgents(root), ["other"]);
  mkdirSync(join(root, ".codex"));
  writeFileSync(join(root, "CLAUDE.md"), "");
  assert.deepEqual(detectAgents(root), ["claude-code", "codex"]);
  assert.deepEqual(parseAgents("none"), []);
  assert.deepEqual(parseAgents("Codex, claude-code,codex"), ["codex", "claude-code"]);
  assert.match(parseAgents("cursor") as string, /must be one of/);
  assert.throws(() => parseConfig('{"statuses":["backlog","done"],"agents":["cursor"]}'), /must be one of/);
  assert.equal(parseConfig('{"statuses":["backlog","done"]}').agents, undefined, "missing stays missing");
});

test("agents: conflicts outside the block are reported, lines inside it are not", () => {
  const root = fresh();
  writeFileSync(join(root, "AGENTS.md"), "# Rules\nTrack work in Linear.\nBranch names start with feature/.\nUse tabs.\n");
  const r = init(root, STATUSES, "0.0.0", false, { agents: ["codex"] });
  assert.equal(r.conflicts.length, 2, r.conflicts.join("\n"));
  assert.match(r.conflicts[0] as string, /AGENTS\.md line 2 .*Linear/);
  assert.match(r.conflicts[1] as string, /line 3/);
  assert.deepEqual(findConflicts(fresh()), []);
  const off = fresh();
  writeFileSync(join(off, "AGENTS.md"), "Track work in Jira.\n");
  assert.deepEqual(init(off, STATUSES, "0.0.0", false, { agents: [] }).conflicts, [], "AI off: nothing to check");
});
