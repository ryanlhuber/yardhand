import { writeFileSync, renameSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { join } from "node:path";
import { ISSUES_DIR, ROADMAP_FILE, TOOL } from "./names.js";
import { findRoot, loadConfig } from "./config.js";
import { scan } from "./scan.js";
import { readIssues, parentField, type Issue } from "./issues.js";
import { withLock } from "./lock.js";
import { tryRemove } from "./commit.js";
import { YardhandError } from "./errors.js";
import { parentOf } from "./ids.js";

const DONE = "done";
const CANCELED = "canceled";

/** Build the roadmap text. Deterministic (no dates), so `validate` can compare it with the file. */
export function buildRoadmap(all: Issue[]): string {
  const issues = all.filter((i): i is Issue & { id: string } => i.id !== null);
  const byId = new Map(issues.map((i) => [i.id, i]));
  const children = new Map<string, (Issue & { id: string })[]>();
  const roots: (Issue & { id: string })[] = [];
  for (const i of issues) {
    const p = parentField(i) ?? (i.fields ? null : parentOf(i.id));
    if (p && byId.has(p) && p !== i.id) {
      children.set(p, [...(children.get(p) ?? []), i]);
    } else {
      roots.push(i);
    }
  }
  const byIdSort = (a: { id: string }, b: { id: string }) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
  roots.sort(byIdSort);
  for (const list of children.values()) list.sort(byIdSort);

  const seen = new Set<string>();
  const descendants = (id: string): (Issue & { id: string })[] => {
    const out: (Issue & { id: string })[] = [];
    for (const c of children.get(id) ?? []) {
      if (seen.has(c.id)) continue;
      out.push(c, ...descendants(c.id));
    }
    return out;
  };

  const tags = (i: Issue & { id: string }, progress: string | null): string => {
    const parts: string[] = [];
    if (progress) parts.push(progress);
    if (i.bug || i.fields?.["kind"] === "bug") parts.push("bug");
    const priority = i.fields?.["priority"];
    if (priority) parts.push(priority);
    if (i.status !== DONE) parts.push(i.status);
    return parts.length ? " · " + parts.join(" · ") : "";
  };
  const progressOf = (id: string): string | null => {
    const d = descendants(id).filter((c) => c.status !== CANCELED);
    return d.length ? `${d.filter((c) => c.status === DONE).length} of ${d.length} done` : null;
  };
  const box = (i: Issue) => (i.status === DONE ? "[x]" : i.status === CANCELED ? "[-]" : "[ ]");

  const lines = ["# Roadmap", "", `<!-- Generated by ${TOOL} roadmap. Do not edit by hand. -->`, ""];
  const render = (i: Issue & { id: string }, level: number): void => {
    if (seen.has(i.id)) return;
    seen.add(i.id);
    if (level === 0) {
      lines.push("", `## ${i.id}  ${i.slug}${tags(i, progressOf(i.id))}`);
    } else {
      lines.push(`${"  ".repeat(level - 1)}- ${box(i)} ${i.id}  ${i.slug}${tags(i, level === 1 ? progressOf(i.id) : null)}`);
    }
    for (const c of children.get(i.id) ?? []) render(c, level + 1);
  };
  for (const r of roots) render(r, 0);
  return lines.join("\n").replace(/\n{3,}/g, "\n\n") + "\n";
}

export interface RoadmapResult {
  text: string;
  path: string | null;
  issues: number;
}

/** Write issues/ROADMAP.md (or just return the text with `stdout`). */
export function roadmap(cwd: string, stdout = false): RoadmapResult {
  const root = findRoot(cwd);
  const config = loadConfig(root);
  return withLock(root, () => {
    const issues = readIssues(root, scan(root, config));
    const text = buildRoadmap(issues);
    if (stdout) return { text, path: null, issues: issues.length };
    const target = join(root, ISSUES_DIR, ROADMAP_FILE);
    const tmp = join(root, ISSUES_DIR, `.${ROADMAP_FILE}.${randomBytes(6).toString("hex")}.tmp`);
    try {
      writeFileSync(tmp, text, { flag: "wx" });
      renameSync(tmp, target);
    } catch (err) {
      tryRemove(tmp);
      throw new YardhandError(`Could not write ${ISSUES_DIR}/${ROADMAP_FILE} (${(err as NodeJS.ErrnoException).code ?? "error"}).`);
    }
    return { text, path: `${ISSUES_DIR}/${ROADMAP_FILE}`, issues: issues.length };
  });
}
